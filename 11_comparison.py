"""11_comparison.py - one page that compares every result of the project.

Reads outputs/results.csv, outputs/unsupervised_results.csv and outputs/runs/*/rounds.csv and writes
COMPARISON.md: overall table, per-seed results, per-class recall, ablation, pseudo-label quality,
published results, and a supervised / unsupervised / semi-supervised summary at the bottom.

Usage: python 11_comparison.py
"""
import numpy as np
import pandas as pd

from common import ROOT, load_config

ORDER = ["supervised", "supervised_hier", "its", "its_plus_A", "its_plus_B", "its_plus_C", "its_plus"]
NAMES = {"supervised": "Supervised (flat)", "supervised_hier": "Supervised (hierarchical)",
         "its": "ITS (Paper 1)", "its_plus_A": "ITS+ A: hierarchical classifier",
         "its_plus_B": "ITS+ B: A + class-adaptive / partial labels",
         "its_plus_C": "ITS+ C: B + volume-context agreement", "its_plus": "ITS+ (full, ours)"}
METRICS = [("accuracy", "Accuracy"), ("macro_f1", "Macro-F1"), ("macro_auc", "Macro-AUC"),
           ("under_grading_rate", "Under-grading rate")]


def ms(s):
    return f"{s.mean() * 100:.2f} ± {s.std() * 100:.2f}"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out + [""]


def main():
    cfg = load_config()
    out = cfg["output_dir"]
    df = pd.read_csv(out / "results.csv")
    df = df[np.isclose(df["fraction"], 0.10)]
    uns = pd.read_csv(out / "unsupervised_results.csv")
    by = {m: df[df["method"] == m].sort_values("seed") for m in ORDER}
    seeds = sorted(df["seed"].unique())
    md = ["# Comparison of all results", "",
          "NEH_UT_2021 (Noor Eye Hospital), classes NORMAL / DRUSEN / CNV. 10% of training cases labelled "
          "(940 B-scans), 8,933 unlabelled. Test set: 4,326 B-scans from 109 cases never used for training or "
          f"model selection. Seeds {', '.join(map(str, seeds))}; values in %, mean ± SD over seeds.", "",
          "Generated by `11_comparison.py` from `outputs/results.csv`.", ""]

    md += ["## 1. All models", ""]
    md += table(["Model", "Seeds"] + [n for _, n in METRICS],
                [[NAMES[m], len(by[m])] + [ms(by[m][c]) for c, _ in METRICS] for m in ORDER])
    md += ["Under-grading rate = share of diseased scans (DRUSEN or CNV) predicted NORMAL; lower is better.", ""]

    md += ["## 2. Accuracy per seed", ""]
    md += table(["Model"] + [f"Seed {s}" for s in seeds] + ["Mean"],
                [[NAMES[m]] + [f"{v * 100:.2f}" for v in by[m]["accuracy"]] + [f"{by[m]['accuracy'].mean() * 100:.2f}"]
                 for m in ORDER])
    gain = (by["its_plus"]["accuracy"].to_numpy() - by["its"]["accuracy"].to_numpy()) * 100
    md += [f"ITS+ minus ITS per seed: {', '.join(f'{g:+.2f}' for g in gain)} points "
           f"(ITS+ ahead on {int((gain > 0).sum())} of {len(gain)} seeds).", ""]

    md += ["## 3. Macro-F1 per seed", ""]
    md += table(["Model"] + [f"Seed {s}" for s in seeds] + ["Mean"],
                [[NAMES[m]] + [f"{v * 100:.2f}" for v in by[m]["macro_f1"]] + [f"{by[m]['macro_f1'].mean() * 100:.2f}"]
                 for m in ORDER])

    md += ["## 4. Recall per class", ""]
    md += table(["Model", "NORMAL", "DRUSEN", "CNV"],
                [[NAMES[m]] + [ms(by[m][f"recall_{c}"]) for c in cfg["classes"]] for m in ORDER])
    md += ["DRUSEN is the hardest class for every model; most of its errors are predictions of NORMAL.", ""]

    md += ["## 5. Ablation: what each component adds", ""]
    steps = ["its", "its_plus_A", "its_plus_B", "its_plus_C", "its_plus"]
    rows, prev = [], None
    for m in steps:
        a = by[m]["accuracy"].mean() * 100
        rows.append([NAMES[m], f"{a:.2f}", "" if prev is None else f"{a - prev:+.2f}",
                     f"{by[m]['under_grading_rate'].mean() * 100:.2f}"])
        prev = a
    md += table(["Configuration", "Accuracy", "Change", "Under-grading rate"], rows)
    md += ["The hierarchical classifier gives the largest step. The later components add about 1.3 points "
           "together, which is smaller than the seed-to-seed spread of ITS+ (SD about 2.8).", ""]

    md += ["## 6. Pseudo-label quality", "",
           "Share of full pseudo-labels that match the hidden true label, averaged over rounds 1-4 "
           "(analysis only; true labels of the unlabelled pool are never used for training or selection).", ""]
    rows = []
    for m in steps:
        vals, cov = [], []
        for s in seeds:
            r = pd.read_csv(out / "runs" / f"{m}_f010_s{s}" / "rounds.csv")
            r = r[r["round"].astype(str).str.isdigit() & (r["round"].astype(str) != "0")]
            r = r[r["kept"].astype(str) == "True"]
            vals.append(r["full_precision"].mean())
            cov.append(r["coverage"].mean())
        rows.append([NAMES[m], f"{np.mean(vals) * 100:.2f}", f"{np.mean(cov) * 100:.2f}"])
    md += table(["Model", "Pseudo-label precision", "Unlabelled scans admitted"], rows)

    md += ["## 7. Published results on NEH_UT_2021 (context only)", "",
           "The papers report 5% and 20% labels, use their own splits and do not report 10%, so these numbers "
           "are not directly comparable.", ""]
    md += table(["Labels", "Supervised [1]", "ITS [1]", "Supervised [2]", "TRIAGE [2]", "Ours"],
                [["5%", "54.78", "64.15", "60.28", "76.88", "-"],
                 ["10%", "-", "-", "-", "-", f"{by['its_plus']['accuracy'].mean() * 100:.2f} "
                  f"(supervised {by['supervised']['accuracy'].mean() * 100:.2f})"],
                 ["20%", "77.05", "88.56", "79.25", "89.66", "-"],
                 ["100%", "87.14", "-", "88.50", "-", "-"]])
    md += ["[1] Alizadeh et al., Diagnostics 2026, 16, 656. [2] Akash et al., arXiv:2608.14321, 2026.", ""]

    md += ["## 8. Supervised vs unsupervised vs semi-supervised", "",
           "Same test set for every row. The unsupervised model uses no training labels: ImageNet "
           "EfficientNet-B0 features, PCA to 50 dimensions and k-means with 3 clusters (`10_unsupervised.py`); "
           "validation labels are used only to name the clusters, and its three rows are k-means seeds.", ""]
    best_sup = "supervised_hier" if by["supervised_hier"]["accuracy"].mean() > by["supervised"]["accuracy"].mean() \
        else "supervised"
    rows = [["Unsupervised", "k-means on ImageNet features", "0", ms(uns["accuracy"]), ms(uns["macro_f1"]),
             ms(uns["macro_auc"]), ms(uns["under_grading_rate"])]]
    for m, kind, name in [("supervised", "Supervised", "EfficientNet-B0, flat head"),
                          ("supervised_hier", "Supervised", "EfficientNet-B0, hierarchical heads"),
                          ("its", "Semi-supervised", "ITS (Paper 1)"),
                          ("its_plus", "Semi-supervised", "ITS+ (ours)")]:
        rows.append([kind, name, "940 + pseudo-labels from 8,933 unlabelled" if kind == "Semi-supervised" else "940",
                     *[ms(by[m][c]) for c, _ in METRICS]])
    md += table(["Learning type", "Model", "Labelled scans used", "Accuracy", "Macro-F1", "Macro-AUC",
                 "Under-grading rate"], rows)
    sup_acc = by[best_sup]["accuracy"].mean() * 100
    md += [f"Semi-supervised ITS+ is {by['its_plus']['accuracy'].mean() * 100 - sup_acc:.2f} points above the best "
           f"supervised model and {by['its_plus']['accuracy'].mean() * 100 - uns['accuracy'].mean() * 100:.2f} "
           "points above unsupervised clustering.", ""]
    (ROOT / "COMPARISON.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
